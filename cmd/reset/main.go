package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"go/types"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"
	"unicode/utf8"

	"golang.org/x/tools/go/packages"
)

const (
	marker   = "generate:reset"
	genFile  = "reset.gen.go"
	genLabel = "// Code generated by cmd/reset; DO NOT EDIT."
)

func main() {
	if err := run(); err != nil {
		log.Fatalf("reset: %v", err)
	}
}

func run() error {
	root, err := moduleRoot()
	if err != nil {
		return err
	}
	out, err := generate(root, "./...")
	if err != nil {
		return err
	}
	for path, data := range out.files {
		old, err := os.ReadFile(path)
		if err == nil && bytes.Equal(old, data) {
			continue
		}
		if err := os.WriteFile(path, data, 0o644); err != nil {
			return err
		}
	}
	for _, path := range out.stale {
		if err := os.Remove(path); err != nil {
			return err
		}
	}
	return nil
}

func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("go.mod not found")
		}
		dir = parent
	}
}

type output struct {
	files map[string][]byte
	stale []string
}

func generate(dir string, patterns ...string) (*output, error) {
	cfg := &packages.Config{
		Dir: dir,
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax |
			packages.NeedTypes | packages.NeedTypesInfo | packages.NeedImports | packages.NeedDeps,
	}
	pkgs, err := packages.Load(cfg, patterns...)
	if err != nil {
		return nil, err
	}
	var errs []error
	for _, pkg := range pkgs {
		for _, e := range pkg.Errors {
			errs = append(errs, e)
		}
	}
	if len(errs) > 0 {
		return nil, errors.Join(errs...)
	}

	marked := make(map[*types.TypeName]bool)
	perPkg := make(map[*packages.Package][]*types.TypeName)
	for _, pkg := range pkgs {
		names, err := findMarked(pkg)
		if err != nil {
			return nil, err
		}
		for _, n := range names {
			marked[n] = true
		}
		perPkg[pkg] = names
	}

	out := &output{files: make(map[string][]byte)}
	for _, pkg := range pkgs {
		pkgDir := packageDir(pkg)
		if pkgDir == "" {
			continue
		}
		path := filepath.Join(pkgDir, genFile)
		names := perPkg[pkg]
		if len(names) == 0 {
			if isGenerated(path) {
				out.stale = append(out.stale, path)
			}
			continue
		}
		src, err := render(pkg, names, marked)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", pkg.PkgPath, err)
		}
		out.files[path] = src
	}
	return out, nil
}

func packageDir(pkg *packages.Package) string {
	if len(pkg.GoFiles) == 0 {
		return ""
	}
	return filepath.Dir(pkg.GoFiles[0])
}

func isGenerated(path string) bool {
	data, err := os.ReadFile(path)
	return err == nil && bytes.HasPrefix(data, []byte(genLabel))
}

func findMarked(pkg *packages.Package) ([]*types.TypeName, error) {
	var names []*types.TypeName
	for _, file := range pkg.Syntax {
		if filepath.Base(pkg.Fset.File(file.Pos()).Name()) == genFile {
			continue
		}
		for _, decl := range file.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts := spec.(*ast.TypeSpec)
				if !hasMarker(gd.Doc) && !hasMarker(ts.Doc) {
					continue
				}
				if _, ok := ts.Type.(*ast.StructType); !ok {
					continue
				}
				if ts.TypeParams != nil {
					return nil, fmt.Errorf("%s: generic structs are not supported", ts.Name.Name)
				}
				obj, ok := pkg.TypesInfo.Defs[ts.Name].(*types.TypeName)
				if !ok {
					continue
				}
				names = append(names, obj)
			}
		}
	}
	sort.Slice(names, func(i, j int) bool { return names[i].Name() < names[j].Name() })
	return names, nil
}

func hasMarker(doc *ast.CommentGroup) bool {
	if doc == nil {
		return false
	}
	for _, c := range doc.List {
		if strings.TrimSpace(strings.TrimPrefix(c.Text, "//")) == marker {
			return true
		}
	}
	return false
}

type renderer struct {
	pkg     *types.Package
	marked  map[*types.TypeName]bool
	current *types.TypeName
	imports map[string]*types.Package
}

func (r *renderer) qualifier(p *types.Package) string {
	if p == r.pkg {
		return ""
	}
	r.imports[p.Path()] = p
	return p.Name()
}

func render(pkg *packages.Package, names []*types.TypeName, marked map[*types.TypeName]bool) ([]byte, error) {
	r := &renderer{pkg: pkg.Types, marked: marked, imports: make(map[string]*types.Package)}

	var body bytes.Buffer
	for _, obj := range names {
		st, ok := obj.Type().Underlying().(*types.Struct)
		if !ok {
			continue
		}
		r.current = obj
		recv := receiverName(obj.Name())
		fmt.Fprintf(&body, "\n// Reset restores %s to its zero state, keeping slice and map storage.\n", obj.Name())
		fmt.Fprintf(&body, "func (%s *%s) Reset() {\n", recv, obj.Name())
		fmt.Fprintf(&body, "if %s == nil {\nreturn\n}\n", recv)
		for i := range st.NumFields() {
			f := st.Field(i)
			if f.Name() == "_" {
				continue
			}
			body.WriteString(r.resetStmt(recv+"."+f.Name(), f.Type()))
		}
		body.WriteString("}\n")
	}

	var src bytes.Buffer
	src.WriteString(genLabel + "\n\n")
	fmt.Fprintf(&src, "package %s\n", pkg.Types.Name())
	if len(r.imports) > 0 {
		paths := make([]string, 0, len(r.imports))
		for p := range r.imports {
			paths = append(paths, p)
		}
		sort.Strings(paths)
		src.WriteString("\nimport (\n")
		for _, p := range paths {
			imp := r.imports[p]
			if path := imp.Path(); path[strings.LastIndex(path, "/")+1:] != imp.Name() {
				fmt.Fprintf(&src, "%s %q\n", imp.Name(), path)
			} else {
				fmt.Fprintf(&src, "%q\n", path)
			}
		}
		src.WriteString(")\n")
	}
	src.Write(body.Bytes())

	formatted, err := format.Source(src.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting generated code: %w", err)
	}
	return formatted, nil
}

func receiverName(typeName string) string {
	r, _ := utf8.DecodeRuneInString(typeName)
	return string(unicode.ToLower(r))
}

func (r *renderer) hasReset(t types.Type) bool {
	named, ok := t.(*types.Named)
	if !ok {
		return false
	}
	if r.marked[named.Obj()] {
		return true
	}
	if _, isPtr := named.Underlying().(*types.Pointer); isPtr {
		return false
	}
	return hasResetMethod(types.NewMethodSet(types.NewPointer(named))) ||
		hasResetMethod(types.NewMethodSet(named))
}

func hasResetMethod(ms *types.MethodSet) bool {
	sel := ms.Lookup(nil, "Reset")
	if sel == nil {
		return false
	}
	sig, ok := sel.Type().(*types.Signature)
	return ok && sig.Params().Len() == 0 && sig.Results().Len() == 0
}

func callUnlessNil(target string) string {
	return fmt.Sprintf("if %s != nil {\n%s.Reset()\n}\n", target, target)
}

func (r *renderer) resetStmt(target string, t types.Type) string {
	under := t.Underlying()
	if _, isIface := under.(*types.Interface); isIface {
		if hasResetMethod(types.NewMethodSet(t)) {
			return callUnlessNil(target)
		}
		return target + " = nil\n"
	}
	if ptr, ok := under.(*types.Pointer); ok {
		if _, named := t.(*types.Named); named {
			return target + " = nil\n"
		}
		if r.isCurrent(ptr.Elem()) {
			return target + " = nil\n"
		}
		if r.hasReset(ptr.Elem()) {
			return callUnlessNil(target)
		}
		return fmt.Sprintf("if %s != nil {\n%s}\n", target, r.resetStmt("*"+target, ptr.Elem()))
	}
	if r.hasReset(t) {
		return target + ".Reset()\n"
	}

	switch u := under.(type) {
	case *types.Basic:
		switch {
		case u.Info()&types.IsBoolean != 0:
			return target + " = false\n"
		case u.Info()&types.IsString != 0:
			return target + " = \"\"\n"
		case u.Info()&types.IsNumeric != 0:
			return target + " = 0\n"
		}
	case *types.Slice:
		return fmt.Sprintf("%s = %s[:0]\n", target, target)
	case *types.Map:
		return fmt.Sprintf("clear(%s)\n", target)
	case *types.Array, *types.Struct:
		return fmt.Sprintf("%s = %s{}\n", target, types.TypeString(t, r.qualifier))
	}
	return target + " = nil\n"
}

func (r *renderer) isCurrent(t types.Type) bool {
	named, ok := t.(*types.Named)
	return ok && named.Obj() == r.current
}
